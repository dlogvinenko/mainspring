"""Tests for the generated GitHub Pages docs site source."""

from __future__ import annotations

import os
import subprocess
import sys
from pathlib import Path

import pytest

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parent))

import docs_site  # noqa: E402


REPO_ROOT = HERE.parents[1]
SCRIPT = HERE.parent / "docs_site.py"
PAGES_WORKFLOW = REPO_ROOT / ".github" / "workflows" / "pages.yml"


# Scenario: P-Comp-7 needs a Jekyll-compatible docs source generated from
# canonical committed Markdown.
# Expected: The generator writes front-matter pages for the PRD, Method,
# playbook, guide, and market positioning without copying from an alternate
# planning source.
def test_docs_site_generates_jekyll_pages(tmp_path: Path) -> None:
    out = tmp_path / "site"

    written = docs_site.build_site(REPO_ROOT, out, clean=True)

    assert (out / docs_site.MARKER).is_file()
    assert out / "prd.md" in written
    assert (
        (out / "_config.yml")
        .read_text(encoding="utf-8")
        .startswith("title: Mainspring")
    )
    layout = (out / "_layouts/default.html").read_text(encoding="utf-8")
    assert "{{ content }}" in layout
    assert 'meta name="description"' in layout
    assert "page.description | default: site.description | escape" in layout
    assert 'meta property="og:site_name"' in layout
    assert 'meta property="og:title"' in layout
    assert 'meta property="og:description"' in layout
    assert 'meta name="twitter:card" content="summary"' in layout
    assert 'meta name="theme-color" content="#116a62"' in layout
    for slug, source in {
        page.slug: page.source.as_posix() for page in docs_site.DOC_PAGES
    }.items():
        text = (out / f"{slug}.md").read_text(encoding="utf-8")
        assert "layout: default" in text
        assert "description: " in text
        assert f"permalink: /{slug}/" in text
        assert f"Source: `{source}`" in text
    index = (out / "index.md").read_text(encoding="utf-8")
    assert "Product Requirements Document (PRD)-first" in index
    assert "AI coding agent orchestration" in index
    assert "Start with the Operator Guide" in index
    assert "{{ '/guide/' | relative_url }}" in index
    assert "{{ '/prd/' | relative_url }}" in index
    assert index.index("{{ '/guide/' | relative_url }}") < index.index(
        "{{ '/prd/' | relative_url }}"
    )
    assert "{{ '/competitive-analysis/' | relative_url }}" in index
    assert "{{ '/architecture/' | relative_url }}" in index
    assert "{{ '/metrics/' | relative_url }}" in index
    method = (out / "method.md").read_text(encoding="utf-8")
    assert "uses on itself" in method
    assert "dogfood" not in method.lower()
    playbook = (out / "playbook.md").read_text(encoding="utf-8")
    normalized_playbook = " ".join(playbook.split())
    assert "title: Maintainer Playbook" in playbook
    assert "This is not the first-read user guide" in normalized_playbook


# Scenario: A clean build should not remove arbitrary operator files.
# Expected: --clean only removes a directory previously marked by this
# generator.
def test_docs_site_clean_refuses_unmarked_directory(tmp_path: Path) -> None:
    out = tmp_path / "site"
    out.mkdir()
    (out / "manual.txt").write_text("keep me", encoding="utf-8")

    with pytest.raises(SystemExit) as exc:
        docs_site.build_site(REPO_ROOT, out, clean=True)

    assert "refusing to clean unmarked docs-site output" in str(exc.value)
    assert (out / "manual.txt").is_file()


# Scenario: A misplaced marker should not make broad directories deletable.
# Expected: --clean refuses the repository root and parent paths even when the
# marker exists.
def test_docs_site_clean_refuses_broad_marked_directories(tmp_path: Path) -> None:
    repo = tmp_path / "repo"
    repo.mkdir()
    parent_marker = tmp_path / docs_site.MARKER
    repo_marker = repo / docs_site.MARKER
    parent_marker.write_text("generated by py/docs_site.py", encoding="utf-8")
    repo_marker.write_text("generated by py/docs_site.py", encoding="utf-8")

    for output in (tmp_path, repo):
        with pytest.raises(SystemExit) as exc:
            docs_site.build_site(repo, output, clean=True)

        assert "refusing to clean broad docs-site output" in str(exc.value)
        assert output.exists()


# Scenario: The CLI is what local smoke tests and GitHub Actions call.
# Expected: It generates the same site source and exits successfully.
def test_docs_site_cli_generates_output(tmp_path: Path) -> None:
    out = tmp_path / "site"

    result = subprocess.run(
        [sys.executable, str(SCRIPT), "--output", str(out), "--clean"],
        capture_output=True,
        text=True,
        check=False,
    )

    assert result.returncode == 0
    assert "docs-site: generated" in result.stdout
    assert (out / "guide.md").is_file()
    assert (out / "competitive-analysis.md").is_file()
    assert (out / "architecture.md").is_file()
    assert (out / "metrics.md").is_file()
    config = (out / "_config.yml").read_text(encoding="utf-8")
    assert "Product Requirements Document (PRD)-first" in config
    assert "AI coding agent orchestration" in config


