# Scenario: P-Comp-7 asks for GitHub Pages with automatic docs rebuilds.
# Expected: The workflow builds generated Jekyll source and keeps deployment
# gated behind an owner-controlled repo variable until Pages is enabled.
def test_pages_workflow_builds_generated_jekyll_source() -> None:
    text = PAGES_WORKFLOW.read_text(encoding="utf-8")

    assert "py/docs_site.py" in text
    assert "actions/jekyll-build-pages" in text
    assert "actions/upload-pages-artifact" in text
    assert "actions/deploy-pages" in text
    assert "actions/checkout@v6" in text
    assert "actions/setup-python@v6" in text
    assert "actions/upload-pages-artifact@v5" in text
    assert "actions/deploy-pages@v5" in text
    assert "actions/checkout@v4" not in text
    assert "actions/setup-python@v5" not in text
    assert "MAINSPRING_ENABLE_PAGES_DEPLOY" in text
    assert "docs/**" in text
    assert "workflow_dispatch" in text
    top_level = text.split("jobs:", maxsplit=1)[0]
    assert "contents: read" in top_level
    assert "pages: write" not in top_level
    assert "id-token: write" not in top_level
    deploy_job = text.split("  deploy:", maxsplit=1)[1]
    assert "permissions:" in deploy_job
    assert "pages: write" in deploy_job
    assert "id-token: write" in deploy_job
    build_job = text.split("  build:", maxsplit=1)[1].split("  deploy:", maxsplit=1)[0]
    assert "permissions:" in build_job
    assert "contents: read" in build_job
    assert "pages: write" not in build_job
    assert "id-token: write" not in build_job


# Every probe creates all source/target content under pytest's owned TMP.
def _synthetic_repo(tmp_path: Path) -> Path:
    repo = tmp_path / "synthetic-repo"
    (repo / ".git").mkdir(parents=True)
    for page in docs_site.DOC_PAGES:
        source = repo / page.source
        source.parent.mkdir(parents=True, exist_ok=True)
        source.write_text(
            f"# Synthetic {page.slug}\n\nSynthetic source body.\n", encoding="utf-8"
        )
    return repo


def _source_bytes(repo: Path) -> dict[str, bytes]:
    return {
        page.source.as_posix(): (repo / page.source).read_bytes()
        for page in docs_site.DOC_PAGES
    }


@pytest.mark.parametrize("alias", [False, True])
def test_nonclean_source_output_is_refused_without_mutation(
    tmp_path: Path, alias: bool
) -> None:
    repo = _synthetic_repo(tmp_path)
    before = _source_bytes(repo)
    output = repo / "docs"
    if alias:
        output = tmp_path / "source-alias"
        output.symlink_to(repo / "docs", target_is_directory=True)
    with pytest.raises(SystemExit) as exc:
        docs_site.build_site(repo, output, clean=False)
    assert "source" in str(exc.value)
    assert _source_bytes(repo) == before
    assert not (repo / "docs" / docs_site.MARKER).exists()


def test_marked_source_directory_is_not_clean_authority(tmp_path: Path) -> None:
    repo = _synthetic_repo(tmp_path)
    before = _source_bytes(repo)
    output = repo / "docs"
    (output / docs_site.MARKER).write_text(
        "generated by py/docs_site.py\n", encoding="utf-8"
    )
    with pytest.raises(SystemExit) as exc:
        docs_site.build_site(repo, output, clean=True)
    assert "overlapping canonical source" in str(exc.value)
    assert _source_bytes(repo) == before


@pytest.mark.parametrize("target_name", ["guide.md", docs_site.MARKER])
def test_output_file_alias_cannot_overwrite_source(
    tmp_path: Path, target_name: str
) -> None:
    repo = _synthetic_repo(tmp_path)
    before = _source_bytes(repo)
    output = tmp_path / "site"
    output.mkdir()
    (output / target_name).symlink_to(repo / "docs/guide.md")
    with pytest.raises(SystemExit) as exc:
        docs_site.build_site(repo, output, clean=False)
    assert "overlapping canonical source" in str(exc.value)
    assert _source_bytes(repo) == before


def test_clean_cannot_delete_source_reached_through_source_symlink(
    tmp_path: Path,
) -> None:
    repo = _synthetic_repo(tmp_path)
    output = tmp_path / "site"
    output.mkdir()
    (output / docs_site.MARKER).write_text(
        "generated by py/docs_site.py\n", encoding="utf-8"
    )
    target = output / "source-input.md"
    target.write_text("Synthetic canonical guide input.\n", encoding="utf-8")
    guide = repo / "docs/guide.md"
    # Only replace a newly created fixture input, never a real project file.
    guide.unlink()
    guide.symlink_to(target)
    before = _source_bytes(repo)
    with pytest.raises(SystemExit) as exc:
        docs_site.build_site(repo, output, clean=True)
    assert "canonical source" in str(exc.value)
    assert _source_bytes(repo) == before
    assert target.is_file()


def test_nonclean_incremental_output_policy_remains_supported(tmp_path: Path) -> None:
    repo = _synthetic_repo(tmp_path)
    output = tmp_path / "site"
    output.mkdir()
    manual = output / "custom-asset.txt"
    manual.write_text("Synthetic custom asset.\n", encoding="utf-8")
    before = _source_bytes(repo)
    docs_site.build_site(repo, output, clean=False)
    assert manual.read_text(encoding="utf-8") == "Synthetic custom asset.\n"
    assert (output / docs_site.MARKER).is_file()
    assert _source_bytes(repo) == before


def test_owned_generated_output_still_rebuilds_and_cleans(tmp_path: Path) -> None:
    repo = _synthetic_repo(tmp_path)
    before = _source_bytes(repo)
    output = tmp_path / "site"
    docs_site.build_site(repo, output, clean=False)
    stale = output / "stale-generated.txt"
    stale.write_text("Synthetic stale output.\n", encoding="utf-8")
    docs_site.build_site(repo, output, clean=True)
    assert not stale.exists()
    assert (output / "guide.md").is_file()
    assert _source_bytes(repo) == before


def test_cli_source_overlap_refuses_before_writing(tmp_path: Path) -> None:
    repo = _synthetic_repo(tmp_path)
    before = _source_bytes(repo)
    result = subprocess.run(
        [
            sys.executable,
            str(SCRIPT),
            "--repo-root",
            str(repo),
            "--output",
            str(repo / "docs"),
        ],
        capture_output=True,
        text=True,
        check=False,
    )
    assert result.returncode != 0
    assert "canonical source" in result.stderr
    assert _source_bytes(repo) == before


def test_clean_owned_output_may_remove_its_own_source_alias(tmp_path: Path) -> None:
    repo = _synthetic_repo(tmp_path)
    before = _source_bytes(repo)
    output = tmp_path / "site"
    docs_site.build_site(repo, output, clean=False)
    generated = output / "guide.md"
    generated.unlink()
    generated.symlink_to(repo / "docs/guide.md")
    docs_site.build_site(repo, output, clean=True)
    assert not generated.is_symlink()
    assert generated.is_file()
    assert _source_bytes(repo) == before


def test_nonclean_hardlinked_target_cannot_overwrite_source(tmp_path: Path) -> None:
    repo = _synthetic_repo(tmp_path)
    before = _source_bytes(repo)
    output = tmp_path / "site"
    output.mkdir()
    os.link(repo / "docs/guide.md", output / "guide.md")
    with pytest.raises(SystemExit) as exc:
        docs_site.build_site(repo, output, clean=False)
    assert "overlapping canonical source" in str(exc.value)
    assert _source_bytes(repo) == before
