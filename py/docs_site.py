def _repo_root() -> Path:
    return Path(__file__).resolve().parents[1]


def _write(path: Path, text: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text.rstrip() + "\n", encoding="utf-8")


def _refuses_broad_clean_target(repo_root: Path, output_dir: Path) -> str | None:
    if output_dir == output_dir.parent:
        return "filesystem root"
    home = Path.home().resolve()
    if output_dir == home:
        return "home directory"
    if output_dir == repo_root or output_dir in repo_root.parents:
        return "repository root or parent"
    return None


def _protect_canonical_sources(
    repo_root: Path, output_dir: Path, *, clean: bool
) -> None:
    sources = [repo_root / page.source for page in DOC_PAGES]
    if clean:
        # Cleanup removes entries inside output, but not symlink targets outside it.
        protected = sources + [source.resolve() for source in sources]
        if any(
            output_dir == source or output_dir in source.parents for source in protected
        ):
            raise SystemExit(
                f"refusing to clean docs-site output overlapping canonical source files: {output_dir}"
            )
        return
    targets = [
        output_dir / MARKER,
        output_dir / "_config.yml",
        output_dir / "_layouts/default.html",
        output_dir / "index.md",
        *(output_dir / f"{page.slug}.md" for page in DOC_PAGES),
    ]
    for target in targets:
        if any(
            target.resolve() == source.resolve()
            or (target.exists() and source.exists() and target.samefile(source))
            for source in sources
        ):
            raise SystemExit(
                f"refusing docs-site output overlapping canonical source files: {output_dir}"
            )


def _clean_output(repo_root: Path, output_dir: Path) -> None:
    unsafe_reason = _refuses_broad_clean_target(repo_root, output_dir)
    if unsafe_reason:
        raise SystemExit(
            f"refusing to clean broad docs-site output ({unsafe_reason}): {output_dir}"
        )
    _protect_canonical_sources(repo_root, output_dir, clean=True)
    if output_dir.exists():
        marker = output_dir / MARKER
        if not marker.exists():
            raise SystemExit(
                f"refusing to clean unmarked docs-site output: {output_dir}"
            )
        shutil.rmtree(output_dir)
    output_dir.mkdir(parents=True, exist_ok=True)
    _write(output_dir / MARKER, "generated by py/docs_site.py")


def _front_matter(page: DocPage) -> str:
    return "\n".join(
        [
            "---",
            "layout: default",
            f"title: {page.title}",
            f"description: {page.summary}",
            f"permalink: /{page.slug}/",
            f"source_path: {page.source.as_posix()}",
            "---",
            "",
        ]
    )


def _page_body(repo_root: Path, page: DocPage) -> str:
    source_path = repo_root / page.source
    if not source_path.is_file():
        raise SystemExit(f"missing docs source: {page.source}")
    source = source_path.read_text(encoding="utf-8").strip()
    return (
        _front_matter(page)
        + f"> Source: `{page.source.as_posix()}`.\n\n"
        + source
        + "\n"
    )


def _index() -> str:
    links = "\n".join(
        f"- [{page.title}]({{{{ '/{page.slug}/' | relative_url }}}}) - {page.summary}"
        for page in DOC_PAGES
    )
    return f"""---
layout: default
title: Mainspring Docs
permalink: /
---

# Mainspring Docs

Product Requirements Document (PRD)-first AI coding agent orchestration for
production-grade software delivery. Turn intent into reviewed, auditable work.

Start with the Operator Guide, then use the Method and Competitive Analysis to
understand why the workflow exists. The Product Requirements Document (PRD) and
Maintainer Playbook are published as auditable project truth, not as the first
thing a new operator needs to read.

## Documentation

{links}

## Release Truth

The PRD remains the source of truth. This site is a published view of committed
docs, not a separate planning surface.
"""


