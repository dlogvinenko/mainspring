def _config() -> str:
    return """title: Mainspring
description: Product Requirements Document (PRD)-first AI coding agent orchestration for production-grade software delivery.
markdown: kramdown
plugins: []
exclude:
  - README.md
  - .mainspring-docs-site
"""


def build_site(repo_root: Path, output_dir: Path, clean: bool = False) -> list[Path]:
    repo_root = repo_root.resolve()
    output_dir = output_dir.resolve()
    if clean:
        _clean_output(repo_root, output_dir)
    else:
        _protect_canonical_sources(repo_root, output_dir, clean=False)
        output_dir.mkdir(parents=True, exist_ok=True)
        _write(output_dir / MARKER, "generated by py/docs_site.py")

    _write(output_dir / "_config.yml", _config())
    _write(output_dir / "_layouts" / "default.html", _layout())
    _write(output_dir / "index.md", _index())

    written = [
        output_dir / "_config.yml",
        output_dir / "_layouts" / "default.html",
        output_dir / "index.md",
    ]
    for page in DOC_PAGES:
        target = output_dir / f"{page.slug}.md"
        _write(target, _page_body(repo_root, page))
        written.append(target)
    return written


def parse_args(argv: list[str]) -> argparse.Namespace:
    parser = argparse.ArgumentParser(
        description="Generate Jekyll source for the Mainspring docs site."
    )
    parser.add_argument(
        "--repo-root",
        type=Path,
        default=_repo_root(),
        help="Repository root containing docs/.",
    )
    parser.add_argument(
        "--output",
        type=Path,
        default=_repo_root() / "build" / "docs-site-source",
        help="Output directory for generated Jekyll source.",
    )
    parser.add_argument(
        "--clean",
        action="store_true",
        help="Remove a previously generated output directory before writing.",
    )
    return parser.parse_args(argv)


def main(argv: list[str] | None = None) -> int:
    args = parse_args(sys.argv[1:] if argv is None else argv)
    written = build_site(args.repo_root, args.output, clean=args.clean)
    print(f"docs-site: generated {len(written)} files in {args.output}")
    return 0


if __name__ == "__main__":
    run_cli(main)
